function detect() {
  try { const s = localStorage.getItem('lang'); if (s === 'en' || s === 'fr') return s; } catch (e) {}
  // first of the visitor's own languages that the site speaks (system / browser settings)
  for (const l of (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''])) { if (/^fr\b/i.test(l)) return 'fr'; if (/^en\b/i.test(l)) return 'en'; }
  return 'en';
}
let lang = detect();
function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}
function apply(root) {
  root = root || document;
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach(el => {
    for (const pair of el.dataset.i18nAttr.split(';')) { const [attr, key] = pair.split(':'); if (attr && key) el.setAttribute(attr.trim(), t(key.trim()).replace(/<[^>]+>/g, '')); }
  });
  document.querySelectorAll('.lang-toggle').forEach(b => { b.textContent = t('lang.switch'); b.setAttribute('aria-label', t('lang.switch.label')); b.setAttribute('lang', lang === 'en' ? 'fr' : 'en'); });
  const yr = document.getElementById('yr'); if (yr && !yr.textContent) yr.textContent = new Date().getFullYear();
  const title = document.querySelector('[data-i18n-title]'); if (title) document.title = t(title.dataset.i18nTitle) + ' · aivancity Tech Club';
}
function set(l) {
  if (l !== 'en' && l !== 'fr') return;
  lang = l; try { localStorage.setItem('lang', l); } catch (e) {}
  apply(); window.dispatchEvent(new CustomEvent('langchange', { detail: l }));
}
/* pick(obj, 'title') → obj.title_fr in French when present, else obj.title */
function pick(obj, field) { return (lang === 'fr' && obj && obj[field + '_fr'] != null && obj[field + '_fr'] !== '') ? obj[field + '_fr'] : obj && obj[field]; }
const locale = () => (lang === 'fr' ? 'fr-FR' : 'en-GB');

